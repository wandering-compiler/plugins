// Package gen is the agent plugin author's compile-time contract with the
// bundle codegen — v4 plugin model. It holds the typed interfaces
// (EnvConfig, HandlerRegistry) the plugin's RegisterPlugin depends on, plus
// the protoc-generated bindings under pb/.
//
// At staging time the bundle's host codegen synthesises a parallel `gen/`
// package with the same exported types populated for the activation; the
// staging import rewrite swaps `<go_module>/gen` for the per-activation staged
// path so the authored code links against the codegen-emitted types with no
// text edits. The local gen/pb stubs are author-only (regenerated by
// `w17ctl plugin gen-pb`); the bundle uses its own per-activation pb.
//
// ClientSet is declared even though this plugin owns no tables and uses none
// of it. The v4 codegen emits a ClientSet and a three-argument RegisterPlugin
// for EVERY plugin, so a plugin that omits them does not link — which is how
// this one shipped unusable: the author-side contract said two arguments, the
// bundle-side wiring called three, and nothing compared them until a consumer
// ran `go build`.
//
// That the plugin ignores what it is handed is a fact about this plugin, not a
// reason to narrow the shared contract.
package gen

import (
	"context"
	"github.com/wandering-compiler/sdk/go/service/secret"

	pb "github.com/wandering-compiler/platform/plugins/agent/gen/pb"
)

// EnvConfig is the plugin's typed configuration, one field per `env:` entry in
// plugin.yaml. Secret-marked entries (`secret: true`) surface as secret.String
// — a value revealed once, at wiring time, rather than a string that can be
// logged by accident.
type EnvConfig struct {
	// Provider selects the backend driver. v1: "azure_openai" only; any other
	// value fails loud at RegisterPlugin rather than at the first call.
	Provider string

	// Endpoint is the provider base URL. Required: there is no default,
	// because a wrong default is a call to somebody else's deployment.
	Endpoint string

	// APIKey is the provider API key, revealed at wiring time.
	//
	// APIKey and not ApiKey: the codegen upper-cases a small initialism set
	// whole (`api`, `url`, `id`, `http`, …) when it turns a manifest name into
	// a Go field, and pluginwire references the name IT produces.
	APIKey secret.String

	// APIVersion is the Azure OpenAI API version. The Responses API is
	// version-gated, so this is a knob rather than a constant.
	APIVersion string

	// DefaultModel applies when a request leaves ModelSpec.id empty. Optional:
	// unset means every caller must name their own model.
	DefaultModel string

	// MaxOutputTokens applies when a request leaves max_tokens at zero. A
	// default, NOT a ceiling the caller cannot exceed.
	MaxOutputTokens int

	// RequestTimeoutSeconds is the per-call deadline. The caller's own context
	// deadline still wins when it is shorter.
	RequestTimeoutSeconds int
}

// HandlerRegistry is how the plugin hands its server implementation to the
// bundle.
type HandlerRegistry interface {
	RegisterAgentServiceServer(impl pb.AgentServiceServer)
	// RegisterShutdown hands the bundle's drain loop a hook to run at
	// teardown. The usage writer is asynchronous, so without one a process
	// that exits — a CLI, an eval, a batch job — takes its queue with it:
	// a consumer measured a short run writing ZERO rows and a longer one
	// keeping only the batches that happened to tick before it ended.
	RegisterShutdown(fn func(ctx context.Context) error)
}

// ClientSet is the bundle's typed in-process clients. This plugin uses none of
// them — it owns no tables — but the contract is shared, so it is declared.
//
// Empty on purpose: a plugin declares the methods it CALLS, and this one calls
// none. Widening it to mirror the emitter would be describing somebody else's
// storage tier in a package that never touches it.
type ClientSet interface{}
